import assert from 'node:assert/strict';
import {writeFile} from 'node:fs/promises';
import {join} from 'node:path';
import {createRequire} from 'node:module';
const require=createRequire(new URL('../mels-api/package.json',import.meta.url));
const WebSocket=require('ws');
const [endpoint,origin,folder]=process.argv.slice(2),socket=new WebSocket(endpoint);
await new Promise((resolve,reject)=>{socket.onopen=resolve;socket.onerror=reject;});
let sequence=0;
const pending=new Map(),errors=[],requests=[];
const send=(method,params={},sessionId)=>new Promise((resolve,reject)=>{const id=++sequence;pending.set(id,{resolve,reject});socket.send(JSON.stringify({id,method,params,...(sessionId?{sessionId}:{})}));});
socket.onmessage=event=>{
    const data=JSON.parse(event.data);
    if(data.id){const p=pending.get(data.id);if(!p)return;pending.delete(data.id);data.error?p.reject(new Error(JSON.stringify(data.error))):p.resolve(data.result);}
    else if(data.method==='Runtime.exceptionThrown')errors.push(data.params.exceptionDetails.exception?.description||data.params.exceptionDetails.text);
    else if(data.method==='Network.requestWillBeSent')requests.push(data.params.request.url);
    else if(data.method==='Fetch.requestPaused'){
        const allowed=data.params.request.url.startsWith(origin+'/')||data.params.request.url.startsWith('data:');
        void send(allowed?'Fetch.continueRequest':'Fetch.failRequest',{requestId:data.params.requestId,...(!allowed?{errorReason:'BlockedByClient'}:{})},data.sessionId);
    }
};
const {targetId}=await send('Target.createTarget',{url:'about:blank'});
const {sessionId}=await send('Target.attachToTarget',{targetId,flatten:true});
for(const method of ['Runtime.enable','Page.enable','Network.enable'])await send(method,{},sessionId);
await send('Fetch.enable',{patterns:[{urlPattern:'*'}]},sessionId);
await send('Emulation.setDeviceMetricsOverride',{width:1280,height:1000,deviceScaleFactor:1,mobile:false},sessionId);
await send('Page.addScriptToEvaluateOnNewDocument',{source:'window.argWorkerCount=0;const RealWorker=Worker;window.Worker=class extends RealWorker{constructor(...args){super(...args);window.argWorkerCount++;}};'},sessionId);
const evaluate=async expression=>{const result=await send('Runtime.evaluate',{expression,awaitPromise:true,returnByValue:true},sessionId);if(result.exceptionDetails)throw new Error(result.exceptionDetails.exception?.description||JSON.stringify(result.exceptionDetails));return result.result.value;};
const until=async expression=>{const deadline=Date.now()+15000;while(!await evaluate(expression)){if(Date.now()>deadline)throw new Error(`Timed out: ${expression}`);await new Promise(resolve=>setTimeout(resolve,100));}};
const set=async(selector,value)=>evaluate(`(()=>{const e=document.querySelector(${JSON.stringify(selector)});e.value=${JSON.stringify(value)};e.dispatchEvent(new Event(e.tagName==='SELECT'?'change':'input',{bubbles:true}));})()`);
const submit=()=>evaluate('document.querySelector("#arg-form").requestSubmit()');
await send('Page.navigate',{url:origin+'/tools/arg/'},sessionId);
await until('document.querySelectorAll("#arg-key-panel input").length===5');
await set('#arg-depth','10');await set('#arg-mode','keyed');
assert.equal(await evaluate('document.querySelector("#arg-depth").value'),'5');
assert.equal(await evaluate('[...document.querySelector("#arg-depth").options].filter(o=>!o.disabled).map(o=>o.value).join(",")'),'1,2,3,4,5');
assert.equal(await evaluate('document.querySelector("#arg-key-panel").hidden'),false);
assert.equal(await evaluate('[...document.querySelectorAll(".arg-parallel-control")].every(e=>e.hidden)'),true);
await set('#arg-input','LXFOPV EF RNHR');await submit();
assert.equal(await evaluate('document.querySelector("#arg-run").disabled'),false);
assert.equal(requests.some(url=>url.includes('arg-english-words')),false,'Empty keys must block before dictionary loading');
assert.equal(await evaluate('document.querySelector("#arg-more-keys").open'),false);
assert.equal(await evaluate('[...document.querySelectorAll("#arg-key-panel input")].filter(e=>e.checkVisibility()).length'),1);
await evaluate('document.querySelector("#arg-more-keys").open=true');
assert.equal(await evaluate('[...document.querySelectorAll("#arg-key-panel input")].filter(e=>e.checkVisibility()).length'),5);
await set('#arg-key-0','LEMON');await set('#arg-key-1','2 4; 2 4');await submit();
assert.equal(await evaluate('document.querySelector("#arg-key-1").getAttribute("aria-invalid")'),'true');
assert.equal(requests.some(url=>url.includes('arg-english-words')),false,'Invalid matrices must block search');
await set('#arg-key-1','');await set('#arg-depth','1');await submit();
await until('!document.querySelector("#arg-run").disabled&&!!document.querySelector(".arg-output")');
assert.equal(await evaluate('[...document.querySelectorAll(".arg-output")].some(e=>e.textContent==="ATTACK AT DAWN")'),true);
assert.equal(await evaluate('window.argWorkerCount'),0);
await set('#arg-input','SGVsbG8gV29ybGQ=');await submit();
await until('!document.querySelector("#arg-run").disabled&&[...document.querySelectorAll(".arg-output")].some(e=>e.textContent==="Hello World")');
assert.equal(await evaluate('[...document.querySelectorAll(".arg-result")].find(e=>e.querySelector(".arg-output").textContent==="Hello World").querySelector(".arg-step").getAttribute("href")'),'/tools/arg/reference/#decoder-base64');
await evaluate('[...document.querySelectorAll(".arg-step")].find(e=>e.hash==="#decoder-base64").click()');
assert.equal(await evaluate('location.pathname'),'/tools/arg/reference/');
assert.equal(await evaluate('document.querySelector("#decoder-base64").classList.contains("arg-reference-highlight")'),true);
assert.notEqual(await evaluate('getComputedStyle(document.querySelector("#decoder-base64")).boxShadow'),'none','History API navigation must visibly highlight the decoder card');
await evaluate('location.hash="decoder-hex"');
await until('document.querySelector("#decoder-hex").classList.contains("arg-reference-highlight")');
assert.equal(await evaluate('document.querySelector("#decoder-base64").classList.contains("arg-reference-highlight")'),false);
await evaluate('document.querySelector("[data-arg-page=search]").click()');
assert.equal(await evaluate('document.querySelectorAll(".arg-reference-highlight").length'),0);
if(process.env.ARG_BROWSER_CHECK==='highlight'){
    await writeFile(join(folder,'reference-highlight.png'),Buffer.from((await send('Page.captureScreenshot',{format:'png'},sessionId)).data,'base64'));
    await send('Target.closeTarget',{targetId});await send('Browser.close');socket.close();
    console.log('OK ARG result-link highlight, target switch and clear on search return');
    process.exit(0);
}
await set('#arg-key-1','5, 8');await set('#arg-key-2','3 1 4 2');await set('#arg-key-3','3 3; 2 5');
await evaluate('document.querySelector("#arg-key-panel").scrollIntoView({block:"start"})');
await writeFile(join(folder,'keyed-desktop.png'),Buffer.from((await send('Page.captureScreenshot',{format:'png'},sessionId)).data,'base64'));
await send('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true},sessionId);
assert.equal(await evaluate('document.documentElement.scrollWidth<=innerWidth'),true,'Key inputs overflow the mobile viewport');
assert.equal(await evaluate('getComputedStyle(document.querySelector("#arg-key-fields")).gridTemplateColumns.split(" ").length'),1);
await writeFile(join(folder,'keyed-mobile.png'),Buffer.from((await send('Page.captureScreenshot',{format:'png'},sessionId)).data,'base64'));
await evaluate('MELSI18n.setLanguage("en")');
assert.equal(await evaluate('/[\u3400-\u9fff]/.test(document.querySelector("#arg-key-panel").textContent)'),false);
assert.equal(await evaluate('document.querySelector("#arg-key-0").value'),'LEMON');
await evaluate('MELSI18n.setLanguage("zh-CN")');
await set('#arg-mode','standard');
assert.equal(await evaluate('document.querySelector("#arg-depth").value'),'10','Original mode depth must be restored');
assert.equal(await evaluate('document.querySelector("#arg-key-panel").hidden'),true);
await set('#arg-key-1','invalid');await set('#arg-depth','1');await set('#arg-input','Uryyb Jbeyq');await submit();
await until('!document.querySelector("#arg-run").disabled&&[...document.querySelectorAll(".arg-output")].some(e=>e.textContent==="Hello World")');
await set('#arg-mode','parallel');
assert.equal(await evaluate('[...document.querySelectorAll(".arg-parallel-control")].every(e=>!e.hidden)'),true);
assert.equal(await evaluate('document.querySelector("#arg-key-panel").hidden'),true);
assert.deepEqual(errors,[]);
await writeFile(join(folder,'results.json'),JSON.stringify({checks:['key formats and early validation','real keyed search and unused keys','single thread','depth clamp and restoration','standard/parallel isolation','desktop/mobile layout','English/Chinese round trip'],errors},null,2));
await send('Target.closeTarget',{targetId});await send('Browser.close');socket.close();
console.log('OK ARG browser: formats, real searches, single thread, depth, mode isolation, mobile layout and translations');
